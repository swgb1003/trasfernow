  static Club requireByName(String name) {
    return all.firstWhere(
      (club) => club.name == name,
      orElse: () => throw StateError('Unknown club: $name'),
    );
  }

  static Club? findByName(String name) {
    for (final club in all) {
      if (club.name == name) return club;
    }
    return null;
  }

  static List<Club> byLeague(String league) =>
      all.where((club) => club.league == league).toList(growable: false);
